def p_value(statistic, trend, n_series):
    """MacKinnon's (1994) asymptotic p-value of a Dickey-Fuller or Engle-Granger t statistic (left tail)."""
    table, k = P_VALUES[trend], n_series - 1
    if statistic > table["tau_max"][k]:
        return 1.0
    if statistic < table["tau_min"][k]:
        return 0.0
    coefficients = table["small"][k] if statistic <= table["tau_star"][k] else table["large"][k]
    return float(ndtr(np.polynomial.polynomial.polyval(statistic, coefficients)))


def critical_values(trend, n_series, nobs):
    """MacKinnon's (2010) critical values at 1%, 5% and 10% for a regression of nobs observations."""
    rows = CRITICAL[trend]
    if n_series > len(rows):
        return Result({level: math.nan for level in LEVELS})
    return Result({level: float(np.polynomial.polynomial.polyval(1.0 / nobs, coefficients))
                   for level, coefficients in zip(LEVELS, rows[n_series - 1])})
